static const char *TAG = "web";

// Seconds a receiver record stays reportable; matches ESPNOW_STALE_US in
// espnow.c but /seen only hides entries after that age.
#define SEEN_STALE_US (60LL * 1000 * 1000)

// Symbols generated by embed_binary() in src/CMakeLists.txt. IDF names
// embedded objects after the file's basename, so the shared data/*.html pages
// linked into src/idf/web/ get _binary_<name>_start/_end.
extern const uint8_t index_html_start[] asm("_binary_index_html_start");
extern const uint8_t index_html_end[] asm("_binary_index_html_end");
extern const uint8_t tally_html_start[] asm("_binary_tally_html_start");
extern const uint8_t tally_html_end[] asm("_binary_tally_html_end");
extern const uint8_t director_html_start[] asm("_binary_director_html_start");
extern const uint8_t director_html_end[] asm("_binary_director_html_end");

static uint64_t bitn(uint8_t n)
{
    return (uint64_t)1 << (n - 1);
}

// Same as firstSelectedTally(): the lowest numbered selection wins.
static uint8_t first_selected_tally(uint64_t bits)
{
    for (uint8_t b = 1; b <= 64; b++) {
        if (bits & bitn(b)) {
            return b;
        }
    }
    return 0;
}

// Arduino String::trim() equivalent: strips leading/trailing whitespace in place.
static void trim_in_place(char *s)
{
    char *start = s;
    while (*start != '\0' && isspace((unsigned char)*start)) {
        start++;
    }
    if (start != s) {
        memmove(s, start, strlen(start) + 1);
    }
    size_t len = strlen(s);
    while (len > 0 && isspace((unsigned char)s[len - 1])) {
        s[--len] = '\0';
    }
}

// /config reboots the controller so the new target is picked up cleanly. The
// restart is deferred so the HTTP response is on the wire before the link drops.
static esp_timer_handle_t s_restart_timer;

static void restart_cb(void *arg)
{
    (void)arg;
    ESP_LOGI(TAG, "restarting to apply new config");
    esp_restart();
}

static void schedule_restart(void)
{
    esp_timer_start_once(s_restart_timer, 50 * 1000);  // 50 ms
}

// Same semantics as bitsFromCSV(): every run of digits is a tally number.
static uint64_t bits_from_csv(const char *s)
{
    uint64_t bits = 0;
    unsigned num = 0;
    for (; *s != '\0'; s++) {
        if (*s >= '0' && *s <= '9') {
            num = num * 10 + (unsigned)(*s - '0');
        } else if (num > 0) {
            if (num <= 64) {
                bits |= bitn((uint8_t)num);
            }
            num = 0;
        }
    }
    if (num > 0 && num <= 64) {
        bits |= bitn((uint8_t)num);
    }
    return bits;
}

// Same as parseHexColor(): accumulate nibbles, ignore anything else.
static uint32_t parse_hex_color(const char *s)
{
    uint32_t color = 0;
    for (; *s != '\0'; s++) {
        unsigned char ch = (unsigned char)*s;
        color <<= 4;
        if (ch >= '0' && ch <= '9') {
            color += ch - '0';
        } else if (ch >= 'A' && ch <= 'F') {
            color += ch - 'A' + 10;
        } else if (ch >= 'a' && ch <= 'f') {
            color += ch - 'a' + 10;
        }
    }
    return color;
}

// Copies one query-string value into buf. Returns false when the key is not
// present or the value does not fit.
static bool query_value(httpd_req_t *req, const char *key, char *buf,
                        size_t cap)
{
    size_t len = httpd_req_get_url_query_len(req) + 1;
    if (len <= 1) {
        return false;
    }
    char *query = malloc(len);
    if (query == NULL) {
        return false;
    }
    bool found = false;
    if (httpd_req_get_url_query_str(req, query, len) == ESP_OK) {
        found = httpd_query_key_value(query, key, buf, cap) == ESP_OK;
    }
    free(query);
    return found;
}

static esp_err_t send_embedded(httpd_req_t *req,
                               const uint8_t *start, const uint8_t *end,
                               const char *content_type)
{
    httpd_resp_set_type(req, content_type);
    httpd_resp_set_hdr(req, "Cache-Control", "no-cache");
    return httpd_resp_send(req, (const char *)start, end - start);
}

static esp_err_t root_get(httpd_req_t *req)
{
    return send_embedded(req, index_html_start, index_html_end, "text/html");
}

static esp_err_t tally_page_get(httpd_req_t *req)
{
    return send_embedded(req, tally_html_start, tally_html_end, "text/html");
}

static esp_err_t director_page_get(httpd_req_t *req)
{
    return send_embedded(req, director_html_start, director_html_end,
                         "text/html");
}

static esp_err_t tally_json_get(httpd_req_t *req)
{
    uint64_t program;
    uint64_t preview;
    espnow_get_tally(&program, &preview);

    char body[96];
    int len = snprintf(body, sizeof(body),
                       "{\"program\":%llu,\"preview\":%llu}",
                       (unsigned long long)program,
                       (unsigned long long)preview);
    if (len <= 0) {
        return ESP_FAIL;
    }

    httpd_resp_set_type(req, "application/json");
    return httpd_resp_send(req, body, len);
}

// Mirrors handleConfig(): GET returns the stored URI verbatim (empty on a
// fresh flash, so the config box renders empty), PUT stores it and reboots.
// The 2 KB working buffer is heap allocated: it would not fit the httpd task's
// 4 KB stack.
static esp_err_t config_get(httpd_req_t *req)
{
    char *body = malloc(CONFIG_STR_MAX);
    if (body == NULL) {
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR,
                                   "out of memory");
    }

    esp_err_t err = config_get_raw(body, CONFIG_STR_MAX);
    if (err == ESP_ERR_NOT_FOUND) {
        body[0] = '\0';
    } else if (err != ESP_OK) {
        ESP_LOGW(TAG, "config read failed: %s", esp_err_to_name(err));
        free(body);
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR,
                                   "config read failed");
    }

    httpd_resp_set_type(req, "text/plain");
    err = httpd_resp_sendstr(req, body);
    free(body);
    return err;
}

static esp_err_t config_put(httpd_req_t *req)
{
    if (req->content_len >= CONFIG_STR_MAX) {
        return httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "Body too long");
    }
    char *body = malloc(CONFIG_STR_MAX);
    if (body == NULL) {
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR,
                                   "out of memory");
    }

    int received = 0;
    while (received < req->content_len) {
        int r = httpd_req_recv(req, body + received,
                               req->content_len - received);
        if (r <= 0) {
            if (r == HTTPD_SOCK_ERR_TIMEOUT) {
                continue;
            }
            free(body);
            return ESP_FAIL;
        }
        received += r;
    }
    body[received] = '\0';
    trim_in_place(body);

    if (body[0] != '\0') {
        esp_err_t err = config_set_raw(body);
        if (err != ESP_OK) {
            ESP_LOGE(TAG, "config write failed: %s", esp_err_to_name(err));
            free(body);
            return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR,
                                       "config write failed");
        }
        ESP_LOGI(TAG, "config saved: [%s]", body);
    }
    free(body);

    httpd_resp_set_type(req, "text/plain");
    esp_err_t err = httpd_resp_sendstr(req, "OK");
    schedule_restart();
    return err;
}

static void power_str(char *buf, size_t cap)
{
    espnow_power_t power;
    espnow_get_power(&power);
    snprintf(buf, cap, "ws=%u&wb=%u&wg=%u", power.sleep_ms, power.burst_ms,
             power.burst_gap_ms);
}

static esp_err_t power_get(httpd_req_t *req)
{
    char body[64];
    power_str(body, sizeof(body));
    httpd_resp_set_type(req, "text/plain");
    return httpd_resp_sendstr(req, body);
}

static esp_err_t power_put(httpd_req_t *req)
{
    char body[128];
    if (req->content_len >= (int)sizeof(body)) {
        return httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "Body too long");
    }
    int received = 0;
    while (received < req->content_len) {
        int r = httpd_req_recv(req, body + received,
                               req->content_len - received);
        if (r <= 0) {
            if (r == HTTPD_SOCK_ERR_TIMEOUT) {
                continue;
            }
            return ESP_FAIL;
        }
        received += r;
    }
    body[received] = '\0';

    // Clamp + populate the live tunables, then persist the canonical form so
    // GET always equals what is stored. (The Arduino build stores the raw body,
    // which silently resets the tunables missing from a partial PUT on the next
    // boot.)
    espnow_apply_power_str(body);
    espnow_power_t power;
    espnow_get_power(&power);

    char reply[64];
    power_str(reply, sizeof(reply));
    esp_err_t err = config_set_power_raw(reply);
    if (err != ESP_OK) {
        ESP_LOGW(TAG, "power config write failed: %s", esp_err_to_name(err));
    }

    httpd_resp_set_type(req, "text/plain");
    return httpd_resp_sendstr(req, reply);
}

static esp_err_t seen_get(httpd_req_t *req)
{
    espnow_tally_info_t tallies[ESPNOW_MAX_TALLY];
    espnow_tallies_snapshot(tallies, ESPNOW_MAX_TALLY);
    const int64_t now = esp_timer_get_time();

    httpd_resp_set_type(req, "application/json");
    esp_err_t err = httpd_resp_sendstr_chunk(req, "{\"tallies\":[");
    if (err != ESP_OK) {
        return err;
    }

    bool first = true;
    for (size_t i = 0; i < ESPNOW_MAX_TALLY; i++) {
        if (tallies[i].id == 0) {
            continue;
        }
        int64_t age = now - tallies[i].last_seen_us;
        if (age > SEEN_STALE_US) {
            continue;
        }
        char entry[48];
        int len = snprintf(entry, sizeof(entry), "%s{\"id\":%u, \"seen\":%lld}",
                           first ? "" : ",", tallies[i].id,
                           (long long)(age / 1000000));
        if (len <= 0) {
            continue;
        }
        err = httpd_resp_sendstr_chunk(req, entry);
        if (err != ESP_OK) {
            return err;
        }
        first = false;
    }

    err = httpd_resp_sendstr_chunk(req, "]}");
    if (err != ESP_OK) {
        return err;
    }
    // NULL chunk terminates the chunked response.
    return httpd_resp_sendstr_chunk(req, NULL);
}

// POST /set?i=1,3&camid=2 -- mirrors handleSet().
static esp_err_t set_post(httpd_req_t *req)
{
    char csv[128];
    if (!query_value(req, "i", csv, sizeof(csv))) {
        return httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "Missing i");
    }
    uint64_t bits = bits_from_csv(csv);
    if (bits == 0) {
        return httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "Missing i");
    }

    char value[64];
    if (query_value(req, "camid", value, sizeof(value))) {
        espnow_camid((uint8_t)strtol(value, NULL, 10), &bits);
        ws_broadcast_set("CAMID", value, csv);
    } else if (query_value(req, "brightness", value, sizeof(value))) {
        espnow_brightness((uint8_t)strtol(value, NULL, 10), &bits);
        ws_broadcast_set("BRIGHTNESS", value, csv);
    } else if (query_value(req, "color", value, sizeof(value))) {
        espnow_color(parse_hex_color(value), &bits);
        ws_broadcast_set("COLOR", value, csv);
    } else if (query_value(req, "signal", value, sizeof(value))) {
        espnow_signal((uint8_t)strtol(value, NULL, 10), &bits);
        ws_broadcast_set("SIGNAL", value, csv);
    }

    httpd_resp_set_type(req, "text/plain");
    return httpd_resp_sendstr(req, "OK");
}

// Mirrors handleSwitch(): act on the first selected tally. ATEM switches over
// UDP (queued to the tally task) and OBS through its websocket connection;
// vMix has no switch action at all.
static esp_err_t switch_post(httpd_req_t *req, bool auto_transition)
{
    char csv[128];
    if (!query_value(req, "i", csv, sizeof(csv))) {
        return httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "Missing i");
    }
    uint8_t tally = first_selected_tally(bits_from_csv(csv));
    if (tally == 0) {
        return httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "Missing i");
    }

    switch (g_config.protocol) {
    case PROTOCOL_ATEM:
        atem_request_switch(tally, auto_transition);
        break;
    case PROTOCOL_OBS:
        obs_request_switch(tally, auto_transition);
        break;
    default:
        return httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST,
                                   "Protocol has no switch action");
    }

    httpd_resp_set_type(req, "text/plain");
    return httpd_resp_sendstr(req, "OK");
}

static esp_err_t cut_post(httpd_req_t *req)
{
    return switch_post(req, false);
}

static esp_err_t auto_post(httpd_req_t *req)
{
    return switch_post(req, true);
}

static esp_err_t register_get(httpd_handle_t server, const char *uri,
                              esp_err_t (*handler)(httpd_req_t *))
{
    const httpd_uri_t route = {
        .uri = uri,
        .method = HTTP_GET,
        .handler = handler,
        .user_ctx = NULL,
    };
    return httpd_register_uri_handler(server, &route);
}

static esp_err_t register_method(httpd_handle_t server, const char *uri,
                                 httpd_method_t method,
                                 esp_err_t (*handler)(httpd_req_t *))
{
    const httpd_uri_t route = {
        .uri = uri,
        .method = method,
        .handler = handler,
        .user_ctx = NULL,
    };
    return httpd_register_uri_handler(server, &route);
}

esp_err_t web_start(void)
{
    // Created before httpd_start(): /config's deferred restart must never see
    // a NULL timer if a request lands in the middle of this function.
    const esp_timer_create_args_t timer_args = {
        .callback = restart_cb,
        .name = "web_restart",
    };
    ESP_ERROR_CHECK(esp_timer_create(&timer_args, &s_restart_timer));

    httpd_config_t cfg = HTTPD_DEFAULT_CONFIG();
    // Default cap is 8; this build registers 12 routes.
    cfg.max_uri_handlers = 16;
    // The default of 7 concurrent clients would starve the lwIP socket pool
    // once the protocol clients and the port-81 server are up (each httpd
    // reserves 3 sockets of its own). The UI needs a couple of connections per
    // browser, and lru_purge_enable recycles idle ones.
    cfg.max_open_sockets = 4;
    cfg.lru_purge_enable = true;

    httpd_handle_t server = NULL;
    esp_err_t err = httpd_start(&server, &cfg);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "httpd_start failed: %s", esp_err_to_name(err));
        return err;
    }

    ESP_ERROR_CHECK(register_get(server, "/", root_get));
    ESP_ERROR_CHECK(register_get(server, "/tally", tally_page_get));
    ESP_ERROR_CHECK(register_get(server, "/director", director_page_get));
    ESP_ERROR_CHECK(register_get(server, "/tally.json", tally_json_get));
    ESP_ERROR_CHECK(register_get(server, "/config", config_get));
    ESP_ERROR_CHECK(register_get(server, "/power", power_get));
    ESP_ERROR_CHECK(register_get(server, "/seen", seen_get));

    ESP_ERROR_CHECK(register_method(server, "/set", HTTP_POST, set_post));
    ESP_ERROR_CHECK(register_method(server, "/cut", HTTP_POST, cut_post));
    ESP_ERROR_CHECK(register_method(server, "/auto", HTTP_POST, auto_post));
    ESP_ERROR_CHECK(register_method(server, "/config", HTTP_PUT, config_put));
    ESP_ERROR_CHECK(register_method(server, "/power", HTTP_PUT, power_put));

    ESP_LOGI(TAG, "HTTP server on port %d", cfg.server_port);
    return ESP_OK;
}
