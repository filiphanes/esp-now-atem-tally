// HTTP layer for the pure-IDF controller.
//
// Mirrors the routes of the Arduino WebServer in src/configWebserver.cpp:
//   GET  /             -> data/index.html     (embedded)
//   GET  /tally        -> data/tally.html     (embedded)
//   GET  /director     -> data/director.html  (embedded)
//   GET  /tally.json   -> {"program":N,"preview":N}
//   GET  /seen         -> receiver list with ages
//   GET  /config       -> stored config URI (NVS; empty when never set)
//   PUT  /config       -> store the config URI and reboot into it
//   GET  /power        -> "ws=0&wb=100&wg=20"
//   PUT  /power        -> clamps, applies and persists the tunables
//   POST /set          -> camid/brightness/color/signal for selected tallies
//   POST /cut,/auto    -> switch the first selected tally (ATEM cut/auto,
//                         OBS scene; vMix has no switch action)
//
// /set also broadcasts the Arduino-style "<KEY> <value> <csv>" frame on the
// port-81 WebSocket so the tally pages update their local display.

